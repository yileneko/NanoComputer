start:
    ; ==========================================
    ; 测试 1: 相等 (5 == 5) -> 预期 JZ 触发
    ; ==========================================
    MOV AL, 5
    MOV BL, 5
    CMP AL, BL          ; AL == BL，此时 ZF = 1, CF = 0
    JZ t1_pass          ; JZ 会触发跳转！
    MOV [0x0100], 0     ; 如果没跳，说明 JZ 失败
    JMP t2_start
t1_pass:
    MOV [0x0100], 1     ; 如果跳了，说明 JZ 成功

    ; ==========================================
    ; 测试 2: 小于 (3 < 7) -> 预期 JC 触发
    ; ==========================================
t2_start:
    MOV AL, 3
    MOV BL, 7
    CMP AL, BL          ; AL < BL，发生借位，此时 ZF = 0, CF = 1
    JC t2_pass          ; JC 会触发跳转！
    MOV [0x0101], 0     ; 如果没跳，说明 JC 失败
    JMP t3_start
t2_pass:
    MOV [0x0101], 1     ; 如果跳了，说明 JC 成功

    ; ==========================================
    ; 测试 3: 大于 (9 > 2) -> 预期 JNC 触发
    ; ==========================================
t3_start:
    MOV AL, 9
    MOV BL, 2
    CMP AL, BL          ; AL > BL，无借位，此时 ZF = 0, CF = 0
    JNC t3_pass         ; JNC 会触发跳转！
    MOV [0x0102], 0     ; 如果没跳，说明 JNC 失败
    JMP end_test
t3_pass:
    MOV [0x0102], 1     ; 如果跳了，说明 JNC 成功

end_test:
    HALT
