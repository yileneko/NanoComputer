start:
    ; --- 环境初始化 ---
    MOV AL, 50          ; AL = 50
    MOV BL, 10          ; BL = 10
    MOV [0x0100], 5     ; 内存 [0x0100] = 5
    MOV [0x0200], 20    ; 内存 [0x0200] = 20

    ; --- 测试 1: SUB reg, imm ---
    SUB AL, 5           ; AL = 50 - 5 = 45 (0x2D)

    ; --- 测试 2: SUB reg, reg ---
    SUB AL, BL          ; AL = 45 - 10 = 35 (0x23)

    ; --- 测试 3: SUB reg, [addr] ---
    SUB AL, [0x0100]    ; AL = 35 - 5 = 30 (0x1E)

    ; --- 测试 4: SUB [addr], reg ---
    ; 内存里原来是 20，AL 是 30。20 - 30 会下溢出！
    ; 在 8 位无符号数中，20 - 30 等于 246 (0xF6)
    SUB [0x0200], AL    ; 内存 [0x0200] = 246

    ; --- 测试 5: SUB [addr], imm ---
    SUB [0x0200], 6     ; 内存 [0x0200] = 246 - 6 = 240 (0xF0)

    ; --- 保存结果并停机 ---
    MOV [0x0300], AL    ; 保存最终的 AL
    MOV BL, [0x0200]    ; 把内存里的结果读出来存到 BL
    MOV [0x0301], BL    ; 保存最终的 BL
    HALT
